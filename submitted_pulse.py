MAX_PAGES_TO_CRAWL = 15
REQUEST_TIMEOUT = 10
DELAY_BETWEEN_REQUESTS = 0.5

session = requests.Session()
session.headers.update({'User-Agent': 'PulseModuleExtractorAI/1.0'})

def is_valid_url(url):
    try:
        result = urlparse(url)
        return all([result.scheme in ['http', 'https'], result.netloc])
    except ValueError:
        return False

def clean_text(text):
    text = re.sub(r'\s+', ' ', text)
    text = text.strip()
    return text

def extract_meaningful_content(soup, url):
    for element in soup(["script", "style", "header", "footer", "nav", "aside", "form", "button", "iframe", "noscript"]):
        element.decompose()
    for comment in soup.find_all(string=lambda text: isinstance(text, Comment)):
        comment.extract()

    potential_containers = [
        soup.find('main'), soup.find('article'), soup.find(id='content'),
        soup.find(id='main-content'), soup.find(class_='content'),
        soup.find(class_='main-content'), soup.find(class_='post-content'),
        soup.find(class_='entry-content'), soup.find(role='main'),
        soup.find(class_='article-body'), soup.find(class_='hc-article-body'),
    ]
    content_element = None
    for container in potential_containers:
        if container:
            content_element = container
            logging.debug(f"Found potential main content container: {content_element.name} {content_element.attrs.get('id', '')} {content_element.attrs.get('class', '')} on {url}")
            break
    if not content_element:
        content_element = soup.body
        logging.warning(f"No specific main content container found on {url}, falling back to body.")
        if not content_element:
             logging.error(f"Could not find body tag on {url}. Skipping content extraction.")
             return ""

    text_parts = []
    if content_element:
      for element in content_element.find_all(['h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'p', 'li', 'td', 'th', 'div']):
          element_text = element.get_text(separator=' ', strip=True)
          if element_text and len(element_text) > 10:
              tag_name = element.name.lower()
              prefix = ""
              if tag_name.startswith('h'): prefix = f"\n## {tag_name.upper()}: "
              elif tag_name == 'li': prefix = "\n* "
              elif tag_name in ['td', 'th']: prefix = " | "
              cleaned_part = clean_text(element_text)
              if cleaned_part: text_parts.append(prefix + cleaned_part)

      if not text_parts or len(" ".join(text_parts)) < 100:
          logging.warning(f"Specific tag extraction yielded little text on {url}, using broader get_text().")
          full_text = content_element.get_text(separator='\n', strip=True)
          lines = [clean_text(line) for line in full_text.splitlines() if clean_text(line)]
          text_parts = lines

    return "\n".join(text_parts)

def crawl_website(start_url, max_pages=MAX_PAGES_TO_CRAWL):
    if not is_valid_url(start_url):
        logging.error(f"Invalid start URL: {start_url}")
        return {}, set()
    parsed_start_url = urlparse(start_url)
    base_domain = parsed_start_url.netloc
    start_path = parsed_start_url.path if parsed_start_url.path else "/"
    allowed_prefixes = ["/"]
    if 'support.' in base_domain or 'help.' in base_domain or '/hc/' in start_path:
        allowed_prefixes = ['/hc/', '/support/', '/help/', '/docs/']
        common_hc_segments = ['/hc/en-us', '/support/en-us', '/help/en-us', '/docs/']
        for seg in common_hc_segments:
             if seg in start_path:
                  prefix = start_path.split(seg)[0] + seg
                  if prefix not in allowed_prefixes: allowed_prefixes.append(prefix)
                  break
    logging.info(f"Starting crawl: {start_url} Domain: {base_domain} Prefixes: {allowed_prefixes}")
    urls_to_visit = {start_url}
    visited_urls = set()
    content_map = {}
    pages_crawled = 0
    while urls_to_visit and pages_crawled < max_pages:
        current_url = urls_to_visit.pop()
        if current_url in visited_urls: continue
        time.sleep(DELAY_BETWEEN_REQUESTS)
        logging.info(f"Crawling ({pages_crawled + 1}/{max_pages}): {current_url}")
        try:
            response = session.get(current_url, timeout=REQUEST_TIMEOUT, allow_redirects=True)
            response.raise_for_status()
            final_url = response.url
            if final_url in visited_urls: continue
            visited_urls.add(current_url); visited_urls.add(final_url)
            pages_crawled += 1
            content_type = response.headers.get('content-type', '').lower()
            if 'html' not in content_type:
                logging.warning(f"Skipping non-HTML content ({content_type}) at: {final_url}")
                continue
            soup = BeautifulSoup(response.text, 'html.parser')
            page_title = clean_text(soup.title.string if soup.title else "No Title Found")
            extracted_text = extract_meaningful_content(soup, final_url)
            if extracted_text:
                 content_map[final_url] = f"--- Page: {final_url} ---\nTitle: {page_title}\n\n{extracted_text}\n\n---\n"
                 logging.info(f"Extracted ~{len(extracted_text)} chars from {final_url}")
            else:
                 logging.warning(f"No meaningful content extracted from {final_url}")
                 content_map[final_url] = f"--- Page: {final_url} ---\nTitle: {page_title}\n\n[No meaningful content extracted]\n\n---\n"

            if pages_crawled < max_pages:
                 for link in soup.find_all('a', href=True):
                    href = link['href']
                    absolute_url = urljoin(final_url, href)
                    parsed_absolute_url = urlparse(absolute_url)
                    absolute_url = parsed_absolute_url._replace(fragment="").geturl() # Remove fragment
                    if (is_valid_url(absolute_url) and
                        parsed_absolute_url.netloc == base_domain and
                        absolute_url not in visited_urls and
                        absolute_url not in urls_to_visit and
                        any(parsed_absolute_url.path.startswith(prefix) for prefix in allowed_prefixes)):
                         path_lower = parsed_absolute_url.path.lower()
                         query_lower = parsed_absolute_url.query.lower()
                         if not any(ext in path_lower for ext in ['.pdf', '.zip', '.jpg', '.png', '.gif', '.css', '.js']) and \
                           not any(kw in path_lower for kw in ['/login', '/signup', '/pricing', '/contact', '/blog', '/about']) and \
                           not any(kw in query_lower for kw in ['mailto:', 'tel:']):
                            urls_to_visit.add(absolute_url)
        except requests.exceptions.RequestException as e:
            logging.error(f"Request failed for {current_url}: {e}")
            visited_urls.add(current_url)
        except Exception as e:
            logging.error(f"Error processing {current_url}: {e}")
            visited_urls.add(current_url)
    logging.info(f"Crawling finished. Visited {len(visited_urls)} URLs. Extracted content from {len(content_map)} URLs.")
    return content_map, visited_urls


def generate_modules_with_gemini(all_text_content):
    """Uses Gemini to identify modules/submodules and generate descriptions."""
    if 'model' not in globals() or model is None:
         logging.error("Gemini model is not initialized. Cannot generate modules.")
         return None, "Error: Gemini model was not initialized correctly. Check API Key configuration."

    if not all_text_content:
         logging.error("No text content provided to Gemini.")
         return None, "Error: No text content was extracted from the URL(s)."

    full_context = "\n".join(all_text_content.values())
    max_context_length = 900000
    if len(full_context) > max_context_length:
        logging.warning(f"Context length ({len(full_context)} chars) exceeds limit, truncating.")
        full_context = full_context[:max_context_length]

    prompt = f"""
    Analyze the following documentation content extracted from a help website. Your goal is to identify the key functional modules and their corresponding submodules described in the text.

    Based *only* on the text provided below, perform the following tasks:
    1.  Identify the main top-level modules (major feature areas or categories).
    2.  For each module, provide a concise and accurate description summarizing its purpose, using *only* information present in the text.
    3.  Under each module, identify its relevant submodules (specific tasks or sub-topics).
    4.  For each submodule, provide a concise and accurate description explaining its function, using *only* information present in the text.
    5.  Structure the output *strictly* as a JSON list of objects. Each object represents a module and must have keys: "module" (String), "Description" (String), "Submodules" (Object where keys are submodule names (String) and values are their descriptions (String)). If a module has no clear submodules based on the text, provide an empty object {{}}.

    Example Format:
    [
      {{
        "module": "Module_1",
        "Description": "Detailed description of the module based on text.",
        "Submodules": {{
          "submodule_1a": "Detailed description of submodule 1a based on text."
        }}
      }},
      {{
        "module": "Module_2",
        "Description": "Detailed description of the module based on text.",
        "Submodules": {{}}
      }}
    ]

    IMPORTANT RULES:
    - Base ALL names and descriptions *strictly* on the content provided. Do not invent features or use external knowledge.
    - If text lacks info, make a best effort or omit.
    - Ensure the output is valid JSON. Do not include any text before or after the JSON list (like ```json or ```).

    Documentation Content:
    --- START CONTENT ---
    {full_context}
    --- END CONTENT ---

    JSON Output:
    """
    logging.info(f"Sending prompt to Gemini (Context size: {len(full_context)} chars)...")
    try:
        response = model.generate_content(
            prompt,
            generation_config=genai.types.GenerationConfig(temperature=0.2)
        )
        raw_response_text = response.text.strip()
        if raw_response_text.startswith("```json"): raw_response_text = raw_response_text[7:]
        if raw_response_text.endswith("```"): raw_response_text = raw_response_text[:-3]
        raw_response_text = raw_response_text.strip()
        logging.info("Received response from Gemini.")
        try:
            result_json = json.loads(raw_response_text)
            if not isinstance(result_json, list): raise ValueError("Expected JSON list.")
            for item in result_json:
                if not isinstance(item, dict): raise ValueError("List items must be objects.")
                if not all(k in item for k in ["module", "Description", "Submodules"]): raise ValueError("Module object missing required keys.")
                if not isinstance(item["Submodules"], dict): raise ValueError("'Submodules' key must contain an object.")
            logging.info("Successfully parsed and validated JSON response from Gemini.")
            return result_json, None
        except (json.JSONDecodeError, ValueError) as e:
            logging.error(f"Invalid JSON from Gemini: {e}. Response: {raw_response_text[:500]}...")
            return None, f"Error: AI generated invalid/unexpected JSON format. {e}\nPreview:\n{raw_response_text[:500]}..."
    except Exception as e:
        logging.error(f"Error calling Gemini API: {e}")
        return None, f"Error: Failed to get response from AI. {e}"


