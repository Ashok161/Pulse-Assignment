def run_streamlit_app():
    st.set_page_config(layout="wide", page_title="Pulse Module Extractor")
    st.title("🚀 Pulse - AI Module Extractor for Help Docs")
    st.markdown("Enter help documentation URL(s) (one per line) to extract modules/submodules using AI.")
    st.warning("🚨 **Security Note:** This version uses hardcoded API keys. Do not use in production or shared environments.", icon="⚠️")

    # Check prerequisites again within the app context (model initialization)
    if model is None:
        st.error("🔴 **CRITICAL:** Gemini model could not be initialized in the Streamlit app. This likely means the `GOOGLE_API_KEY` environment variable was not passed correctly during startup. Please check the main Colab script logs and ensure the key is valid.")
        st.stop() # Stop execution if model isn't ready

    default_urls = [
        "https://support.neo.space/hc/en-us",
        "https://wordpress.org/documentation/",
        "https://help.zluri.com/",
        "https://www.chargebee.com/docs/2.0/"
    ]
    url_input = st.text_area("Enter URLs (one per line):", "\\n".join(default_urls[:1]), height=100)

    # Use the globally defined MAX_PAGES_TO_CRAWL from this script's scope
    max_pages_limit = st.slider("Maximum pages to crawl per starting URL:", min_value=1, max_value=50, value=MAX_PAGES_TO_CRAWL, help="Limits crawling depth.")

    if st.button("✨ Extract Modules", type="primary"):
        urls = [url.strip() for url in url_input.splitlines() if url.strip()]
        if not urls:
            st.warning("Please enter at least one valid URL."); st.stop()
        valid_urls = [url for url in urls if is_valid_url(url)]
        invalid_urls = [url for url in urls if not is_valid_url(url)]
        if invalid_urls: st.warning(f"Ignoring invalid URL(s): {', '.join(invalid_urls)}")
        if not valid_urls: st.error("No valid URLs provided."); st.stop()

        st.info(f"Processing {len(valid_urls)} URL(s)... Max pages per URL: {max_pages_limit}")
        all_extracted_content = {}
        all_visited_urls = set()
        crawling_errors = []
        progress_bar = st.progress(0)
        status_text = st.empty()

        status_text.text("Crawling website(s)...")
        for i, url in enumerate(valid_urls):
            status_text.text(f"Crawling ({i+1}/{len(valid_urls)}): {url}...")
            try:
                # Pass the slider value to the crawl function
                content_map, visited = crawl_website(url, max_pages=max_pages_limit)
                all_extracted_content.update(content_map)
                all_visited_urls.update(visited)
                status_text.text(f"Crawled {url}. Found {len(content_map)} pages with content.")
            except Exception as e:
                st.error(f"Error crawling {url}: {e}")
                logging.error(f"Crawling failed for {url}: {e}")
                crawling_errors.append(f"{url}: {e}")
            progress_bar.progress((i + 1) / (len(valid_urls)*2)) # 50% progress after crawling

        if not all_extracted_content:
            st.error("Could not extract any content from the provided URL(s). Possible reasons: Website requires JavaScript, blocks scraping, unusual structure, or all links visited were non-HTML.")
            if crawling_errors: st.subheader("Crawling Errors Encountered:"); st.json(crawling_errors)
            st.stop()

        st.success(f"Crawling complete. Extracted content from {len(all_extracted_content)} pages across {len(valid_urls)} starting URL(s). Total unique pages visited: {len(all_visited_urls)}.")

        status_text.text("🤖 Asking AI to analyze content and identify modules...")
        with st.spinner("AI is thinking... This might take a moment."):
            extracted_data, error_message = generate_modules_with_gemini(all_extracted_content)

        progress_bar.progress(1.0)

        if error_message:
            status_text.error(f"AI Processing Error: {error_message}")
            st.warning("Could not generate structured output. Check logs or try again. The AI might have had trouble with the content or format.")
        elif extracted_data:
            status_text.success("✅ Successfully extracted modules!")
            st.subheader("Extracted Modules and Submodules:")
            st.json(extracted_data)
            with st.expander("Show Raw Extracted Text (Preview - First 5000 chars)"):
                 preview_text = "\\n".join(all_extracted_content.values())[:5000]
                 st.text_area("Raw Text Sent to AI (Preview)", preview_text , height=300)
            with st.expander("Show Visited URLs"):
                 st.write(sorted(list(all_visited_urls)))
        else:
            status_text.error("🔴 AI analysis failed to produce results. No specific error message provided, check logs.")


# --- Main execution block for streamlit_app.py ---
if __name__ == '__main__':
    run_streamlit_app()

